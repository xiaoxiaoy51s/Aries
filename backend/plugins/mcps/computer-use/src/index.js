#!/usr/bin/env node
// index.js — Computer Use MCP Server
//
// Exposes OpenAI Codex computer-use (sky Window2 API) as MCP tools so that ANY
// MCP-capable agent with vision can drive the Windows GUI: list apps/windows,
// read accessibility trees, click by element index OR screenshot coordinates, type text,
// press keys, scroll, set values, drag, launch/activate windows — and return
// screenshots as image content blocks the agent's vision model can actually see.
//
// The heavy lifting is done by OpenAI's codex-computer-use.exe, bundled inside
// the parent computer_use skill at scripts/codex-computer-use.exe. This server
// is a thin, dependency-light Node.js wrapper around that executable's JSON-RPC protocol.

import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";
import { getClient } from "./sky_client.js";

// ── Coercion helpers ────────────────────────────────────────────
// Some MCP clients (notably wrappers that auto-serialize JSON args) forward
// numeric fields as JSON strings. To keep the server robust we accept either
// type at the schema layer and coerce to number at the call site. The lower
// level (SkyClient → codex-computer-use.exe) still receives real numbers.
function num(v) {
  if (v === undefined || v === null || v === "") return undefined;
  if (typeof v === "number") return Number.isFinite(v) ? v : undefined;
  if (typeof v === "string") {
    const n = Number(v);
    return Number.isFinite(n) ? n : undefined;
  }
  return undefined;
}
function int(v) {
  const n = num(v);
  return n === undefined ? undefined : Math.trunc(n);
}
// zod schema that accepts both number and string-number, validated as finite.
const Num = z
  .union([z.number(), z.string()])
  .transform((v, ctx) => {
    const n = num(v);
    if (n === undefined) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: "expected a number" });
      return z.NEVER;
    }
    return n;
  });
const Int = Num.transform((n) => Math.trunc(n));

const server = new McpServer({
  name: "computer-use-mcp-server",
  version: "1.0.0",
});

// ── Window object schema ──────────────────────────────────────────────
// A window is identified by { app, id }. app is an app identifier string
// (e.g. "process:WeChat.exe" or "Microsoft.AutoGenerated.{...}"); id is the
// opaque window handle number returned by list_windows/list_apps.
const WindowSchema = z
  .object({
    app: z
      .string()
      .describe(
        "App identifier from list_apps/list_windows, e.g. \"process:WeChat.exe\" or \"Microsoft.AutoGenerated.{...}\"",
      ),
    id: Num.describe(
      "Opaque window handle id (number or numeric string) returned by discovery tools",
    ),
    title: z.string().optional().describe("Optional window title for reference"),
  })
  .strict()
  .describe("Target window object returned by list_apps / list_windows");

function textBlock(text) {
  return { type: "text", text };
}

// Wrap a get_window_state result's screenshots into image content blocks.
// `state.screenshots[i].url` comes back from codex-computer-use.exe as a
// `data:<mime>;base64,<payload>` URL. The MCP ImageContent schema requires
// `data` to be the raw base64 payload (no prefix) and `mimeType` to be the
// media type. We split the data URL here so MCP clients receive a valid
// ImageContent block.
const DATA_URL_RE = /^data:([^;,]+)?(;base64)?,(.*)$/s;

function parseDataUrl(url) {
  if (typeof url !== "string") return null;
  const m = DATA_URL_RE.exec(url);
  if (!m) return null;
  return {
    mimeType: m[1] || "image/png",
    isBase64: m[2] === ";base64",
    payload: m[3] || "",
  };
}

function screenshotBlocks(state) {
  const blocks = [];
  const shots = (state && state.screenshots) || [];
  for (const s of shots) {
    if (!s || typeof s.url !== "string") continue;
    const parsed = parseDataUrl(s.url);
    if (parsed) {
      blocks.push({
        type: "image",
        data: parsed.payload,
        mimeType: parsed.mimeType,
      });
    } else {
      // Fall back to treating the value as a plain base64 payload.
      blocks.push({ type: "image", data: s.url, mimeType: "image/png" });
    }
  }
  return blocks;
}

// Build a compact text description of window state.
function describeState(state) {
  if (!state) return "(no state returned)";
  const lines = [];
  const win = state.window || {};
  lines.push(
    `Window: app=${win.app ?? "?"} id=${win.id ?? "?"} title=${win.title ?? ""}`,
  );
  if (state.accessibility && state.accessibility.tree) {
    lines.push("Accessibility tree:");
    lines.push(state.accessibility.tree);
    if (state.accessibility.focused_element) {
      lines.push(`Focused: ${state.accessibility.focused_element}`);
    }
    if (state.accessibility.selected_text) {
      lines.push(`Selected text: ${state.accessibility.selected_text}`);
    }
  } else {
    lines.push(
      "(no accessibility tree — this app exposes no UI Automation controls)",
    );
  }
  const shots = state.screenshots || [];
  if (shots.length) {
    lines.push(
      `Screenshots: ${shots.length} image(s) returned as image blocks (use them to locate coordinates).`,
    );
    for (const s of shots) {
      if (s.width && s.height) {
        lines.push(`  - screenshot ${s.id}: ${s.width}x${s.height}`);
      }
    }
  }
  return lines.join("\n");
}

// ── Tool: list_apps ────────────────────────────────────────────────
server.registerTool(
  "list_apps",
  {
    title: "List installed apps",
    description:
      "List installed applications discoverable by computer-use, including whether each is running and its currently open targetable windows.\n\n" +
      "Use this first to discover what apps exist and obtain Window objects. Each returned app has an id (app identifier) and a windows array; each window is a {app, id, title} object you pass to other * tools.\n\n" +
      'Only returns apps that expose discoverable windows. For apps not listed, pass an explicit .exe path/identifier to launch_app (e.g. "process:C:\\\\Path\\\\App.exe").',
    inputSchema: {
      runningOnly: z
        .boolean()
        .default(false)
        .describe("If true, only return apps that are currently running"),
    },
    outputSchema: {
      apps: z.array(z.any()),
    },
    annotations: {
      readOnlyHint: true,
      destructiveHint: false,
      idempotentHint: true,
      openWorldHint: true,
    },
  },
  async ({ runningOnly }) => {
    const client = getClient();
    let apps = await client.listApps();
    if (runningOnly) apps = apps.filter((a) => a.isRunning);
    return {
      content: [textBlock(JSON.stringify(apps, null, 2))],
      structuredContent: { apps },
    };
  },
);

