// Shared helper: capture window state and format it as MCP content blocks.
async function captureWindowState(window, { includeScreenshot, includeText }) {
  const client = getClient();
  const state = await client.getWindowState(window, {
    includeScreenshot,
    includeText,
  });
  const blocks = screenshotBlocks(state);
  const text = describeState(state);
  return {
    content: [textBlock(text), ...blocks],
    structuredContent: {
      description: text,
      screenshotCount: blocks.length,
    },
  };
}

